#!/usr/bin/env python3
"""Writes THIRD_PARTY_LICENSES.md: the licenses of everything compiled into the macOS app.

Covers the runtime dependency graph of `talus-app` on aarch64-apple-darwin (no dev or build-only
crates) plus C code that Cargo metadata does not see: SQLCipher/SQLite (libsqlite3-sys) and
OpenSSL (openssl-src), and the fonts egui embeds. Identical license texts are printed once with
the list of packages that use them. Run from the repository root after changing dependencies:

    python3 scripts/third-party-licenses.py
"""
import hashlib
import json
import os
import subprocess
import sys

TARGET = "aarch64-apple-darwin"
OUT = "THIRD_PARTY_LICENSES.md"
NAMES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "UNLICENSE")
# License files that live below a crate's root.
EXTRA = {
    "epaint_default_fonts": [
        "fonts/OFL.txt",
        "fonts/UFL.txt",
        "fonts/Hack-Regular.txt",
        "fonts/emoji-icon-font-mit-license.txt",
    ],
    "libsqlite3-sys": ["sqlcipher/LICENSE"],
    "openssl-src": ["openssl/LICENSE.txt"],
}
# Build-time crates whose output is linked into the binary (OpenSSL is compiled and linked statically).
LINKED_FROM_BUILD = {"openssl-src"}
NOTES = {
    "libsqlite3-sys": "Bundles SQLCipher (license below) and SQLite, which is in the public domain.",
    "openssl-src": "Bundles OpenSSL 3, licensed under the Apache License 2.0.",
    "epaint_default_fonts": "Bundles the Ubuntu, Hack, Noto Emoji and emoji-icon fonts.",
}


def metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(out)


def runtime_packages(m):
    nodes = {n["id"]: n for n in m["resolve"]["nodes"]}
    pkgs = {p["id"]: p for p in m["packages"]}
    root = next(p["id"] for p in m["packages"] if p["name"] == "talus-app")
    seen, stack = set(), [root]
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if any(k["kind"] is None for k in d["dep_kinds"]):
                stack.append(d["pkg"])
    seen |= {i for i, p in pkgs.items() if p["name"] in LINKED_FROM_BUILD}
    return sorted((pkgs[i] for i in seen if pkgs[i]["source"]), key=lambda p: (p["name"], p["version"]))


def license_files(pkg):
    root = os.path.dirname(pkg["manifest_path"])
    files = []
    for f in sorted(os.listdir(root)):
        if not f.upper().startswith(NAMES):
            continue
        path = os.path.join(root, f)
        # Some crates keep one file per license in a LICENSES/ directory.
        files += [os.path.join(f, g) for g in sorted(os.listdir(path))] if os.path.isdir(path) else [f]
    files += [f for f in EXTRA.get(pkg["name"], []) if os.path.exists(os.path.join(root, f))]
    return [(f, open(os.path.join(root, f), encoding="utf-8", errors="replace").read().strip()) for f in files]


def main():
    pkgs = runtime_packages(metadata())
    texts = {}  # digest -> (title, text, [packages])
    without = []
    canonical = {}
    for p in pkgs:
        label = f"{p['name']} {p['version']}"
        files = license_files(p)
        if not files:
            without.append(p)
            continue
        for name, text in files:
            # Same license, different wrapping: one entry.
            digest = hashlib.sha256(" ".join(text.split()).encode()).hexdigest()
            entry = texts.setdefault(digest, [name, text, []])
            entry[2].append(label)
            upper = name.upper()
            if "MIT" in upper and "MIT" not in canonical:
                canonical["MIT"] = text
            if "APACHE" in upper and "Apache-2.0" not in canonical:
                canonical["Apache-2.0"] = text

    lines = [
        "# Third-party licenses",
        "",
        "Talus is MIT-licensed. The macOS app also contains the software listed below; each part",
        "keeps its own license. Generated by `scripts/third-party-licenses.py` — do not edit by hand.",
        "",
        f"Packages: {len(pkgs)} Rust crates (runtime dependencies for {TARGET}).",
        "",
        "## Notes",
        "",
    ]
    for name, note in NOTES.items():
        lines.append(f"- **{name}**: {note}")
    lines += ["", "## Packages without a license file", "",
              "These crates declare their license in Cargo metadata only; the standard texts are at the end.", ""]
    for p in without:
        authors = ", ".join(p.get("authors") or []) or "the authors"
        repo = p.get("repository") or ""
        lines.append(f"- {p['name']} {p['version']} — {p.get('license') or 'see repository'} — © {authors} {repo}".rstrip())
    lines += ["", "## License texts", ""]
    for name, text, users in sorted(texts.values(), key=lambda e: (-len(e[2]), e[2][0])):
        lines += [f"### {name}", "", "Used by: " + ", ".join(users), "", "```text", text, "```", ""]
    for spdx, text in canonical.items():
        lines += [f"## Standard text: {spdx}", "", "```text", text, "```", ""]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}: {len(pkgs)} packages, {len(texts)} distinct license texts, {len(without)} without files")


if __name__ == "__main__":
    sys.exit(main())
